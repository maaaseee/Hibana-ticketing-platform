  function transferTicket(ticketId: string, newEmail: string): boolean {
    const ticket = tickets.value.find(t => t.id === ticketId)
    if (!ticket) return false
    ticket.customerEmail = newEmail
    ticket.status = 'TRANSFERRED'
    return true
  }

  function addIssuedTickets(eventTitle: string, eventDate: string, venue: string, selectedSeats: Seat[], orderId: string, customerName: string, customerEmail: string, customerDocument?: string) {
    selectedSeats.forEach((seat, idx) => {
      const id = `tkt_${Date.now().toString(36)}_${idx}`
      tickets.value.unshift({
        id,
        orderId,
        eventId: 'chronos-fest-2026',
        eventTitle,
        eventDate,
        venue,
        sector: seat.sector,
        row: seat.row,
        seatNumber: seat.number,
        customerName,
        customerEmail,
        customerDocument: customerDocument || '38.921.402',
        status: 'ISSUED',
        qrPayload: {
          tid: id,
          eid: 'evt_dynamic',
          vid: 'ven_main',
          sec: seat.sector,
          sig: `MEQCIA_${Math.random().toString(36).substring(2, 10)}`,
        },
        totpRemainingSeconds: 15,
        barcode: `${Math.floor(1000000000000000 + Math.random() * 9000000000000000)}`,
      })
    })
  }

